export const normalizeValue = (s) => String(s == null ? '' : s).trim().toLowerCase();

export const buildGroups = (raw) => {
  const counts = {};
  raw.forEach(([, subs]) => subs.forEach((s) => { counts[s] = (counts[s] || 0) + 1; }));
  return raw.map(([name, subs]) => ({
    name,
    subs: subs.map((label) => ({ label, value: counts[label] > 1 ? `${label} (${name})` : label })),
  }));
};

export const EDUCATION_GROUPS = buildGroups(RAW_EDUCATION);
export const JOB_GROUPS = buildGroups(RAW_JOB);

// Maps a stored value back to { category, sub }. Exact match first, then trimmed/case-insensitive.
export const findInGroups = (groups, storedValue) => {
  if (storedValue == null || String(storedValue).trim() === '') return null;
  for (const category of groups) {
    const sub = category.subs.find((s) => s.value === storedValue);
    if (sub) return { category, sub };
  }
  const n = normalizeValue(storedValue);
  for (const category of groups) {
    const sub = category.subs.find((s) => normalizeValue(s.value) === n);
    if (sub) return { category, sub };
  }
  return null;
};
